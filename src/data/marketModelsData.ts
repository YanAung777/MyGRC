export function convertMarketModelToRecord(m: MarketModelAssessment, workspaceId: string = "ws-1", approver: string = "Security Architect"): ModelRecord {
  return {
    id: `mod-${m.id.replace("mkt-", "")}`,
    workspaceId,
    provider: m.provider,
    name: m.name,
    version: m.version,
    status: m.recommendedStatus,
    approver,
    statusDate: new Date().toLocaleDateString("en-GB", { day: "2-digit", month: "2-digit", year: "numeric" }).replace(/\//g, "-"),
    useCasesCount: 0,
    securityScore: m.securityScore,
    zeroDataRetention: m.zeroDataRetention,
    trainingOptOut: m.trainingOptOut,
    soc2Certified: m.soc2Certified,
    iso27001Certified: m.iso27001Certified,
    hipaaCompliant: m.hipaaCompliant,
    euAiActTier: m.euAiActTier,
    dataResidency: m.dataResidency,
    assessmentDate: new Date().toISOString().split("T")[0],
    recommendedStatus: m.recommendedStatus,
    riskLevel: m.securityScore >= 85 ? "LOW" : m.securityScore >= 70 ? "MEDIUM" : m.securityScore >= 50 ? "HIGH" : "CRITICAL",
    notes: m.notes,
    sourceUrl: m.privacyPolicyUrl,
    lastScannedAt: m.lastScannedAt,
    scannerFeed: "Weekly GRC Market Continuous Review",
    vulnerabilitiesCount: m.cveVulnerabilities,
    guardrailsVerified: m.jailbreakRobustness === "Excellent" || m.jailbreakRobustness === "Good"
  };
}
